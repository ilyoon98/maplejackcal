// Public static output is kept separate from server code and browser binaries.
'use strict';
const fs=require('node:fs');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const root=path.resolve(__dirname,'..');
const output=path.resolve(root,'public');
const marker=path.join(output,'.generated-by-maplejackcal');
if(path.dirname(output)!==root||path.basename(output)!=='public')throw new Error('Unexpected static output directory');
if(fs.existsSync(output)){
  if(!fs.existsSync(marker))throw new Error('public/ already exists and is not generated by this build');
  fs.rmSync(output,{recursive:true,force:true});
}
execFileSync(process.execPath,[path.join(__dirname,'build_coin_shop_data.js')],{cwd:root,stdio:'inherit'});
fs.mkdirSync(output,{recursive:true});
fs.writeFileSync(marker,'Generated static output. Edit the source files in the repository root.\n');
const excluded=new Set(['package.json','package-lock.json','vercel.json']);
for(const entry of fs.readdirSync(root,{withFileTypes:true})){
  if(entry.isFile()&&/\.(?:html|css|js|json|png|webp|jpe?g|ico|svg|woff2?)$/.test(entry.name)&&!excluded.has(entry.name)&&!entry.name.startsWith('calculator-audit-'))fs.copyFileSync(path.join(root,entry.name),path.join(output,entry.name));
}
for(const directory of ['icons','capture-guide','vendor','herb_idle_assets'])if(fs.existsSync(path.join(root,directory)))fs.cpSync(path.join(root,directory),path.join(output,directory),{recursive:true});
console.log('Static pages and assets prepared in public/');
