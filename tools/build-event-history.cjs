// 메이플스토리 홈페이지의 종료된 이벤트 목록을 모아 event_history.js를 만든다.
// 넥슨 Open API의 이벤트 공지는 최근 것만 주므로 접속 기록의 지난 이벤트 표시에 쓴다.
// node tools/build-event-history.cjs   (접속 기록 API 첫날 2023-12-21 이전에 끝난 이벤트에서 멈춘다)
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const LIST_URL = 'https://maplestory.nexon.com/News/Event/Closed?page=';
const STOP_BEFORE = '2023-12-21';
const MAX_PAGES = 80;

function decode(text) {
  // "수정" 표시(<em class="modify_common">)와 남은 태그를 걷어낸다
  text = text.replace(/<em class="modify_common"[^>]*>[\s\S]*?<\/em>/g, '').replace(/<[^>]+>/g, '');
  return text.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/\s+/g, ' ').trim();
}

function parse(html) {
  const events = [];
  const item = /Closed\/(\d+)\?page=\d+">\s*<em class="event_listMt">([\s\S]*?)<\/em>\s*<\/a>[\s\S]*?<dd class="date">\s*<p>(\d{4})\.(\d{2})\.(\d{2}) ~ (\d{4})\.(\d{2})\.(\d{2})<\/p>/g;
  let m;
  while ((m = item.exec(html))) {
    events.push({ id: m[1], title: decode(m[2]), from: `${m[3]}-${m[4]}-${m[5]}`, to: `${m[6]}-${m[7]}-${m[8]}` });
  }
  return events;
}

async function main() {
  const all = new Map();
  for (let page = 1; page <= MAX_PAGES; page++) {
    const response = await fetch(LIST_URL + page, { headers: { 'user-agent': 'Mozilla/5.0 (maplejackcal event-history builder)' } });
    if (!response.ok) throw new Error(`page ${page}: HTTP ${response.status}`);
    const events = parse(await response.text());
    if (!events.length) break;
    events.forEach(event => all.set(event.id, event));
    console.log(`page ${page}: ${events.length}개 (${events[events.length - 1].from})`);
    if (events.every(event => event.to < STOP_BEFORE)) break;
    await new Promise(resolve => setTimeout(resolve, 800));
  }
  const list = [...all.values()].filter(event => event.to >= STOP_BEFORE)
    .sort((a, b) => a.from.localeCompare(b.from) || Number(a.id) - Number(b.id));
  fs.writeFileSync(path.join(root, 'event_history.js'),
    '// Generated by tools/build-event-history.cjs from the MapleStory closed-event list. Do not edit.\n' +
    '(function (root) {\n  var data = ' + JSON.stringify(list, null, 0).replace(/\},\{/g, '},\n    {') +
    ';\n  if (typeof module === "object" && module.exports) module.exports = data;\n  else root.MapleEventHistory = data;\n})(typeof globalThis !== "undefined" ? globalThis : this);\n');
  console.log(`event_history.js: ${list.length}개`);
}

main().catch(error => { console.error(error); process.exit(1); });
