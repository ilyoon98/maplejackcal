// JSON is canonical; the script copy also works when the page is opened with file://.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'equipment_data.json'), 'utf8'));
const names = new Set();
for(const family of data.families||[]){
  if(!family.prefix||!Number.isInteger(family.level)||family.level<1||family.level>300||!family.slot||!family.set||!family.sources?.length)throw new Error('Invalid equipment family: '+family.prefix);
}
for (const item of data.items) {
  if (!item.name || !Number.isInteger(item.level) || item.level < 1 || item.level > 300 || !item.slot || !item.set || !Array.isArray(item.aliases) || !item.sources?.length) throw new Error('Invalid equipment: ' + item.name);
  for (const name of [item.name, ...item.aliases]) {
    const key = name.normalize('NFC').replace(/\s+/g, '').toLowerCase();
    if (!key || names.has(key)) throw new Error('Duplicate equipment name: ' + name);
    names.add(key);
  }
}
const output = '// Generated by node tools/build-equipment-data.cjs; edit equipment_data.json.\n' +
  '(function(root){\n  const data = ' + JSON.stringify(data, null, 2) + ';\n' +
  "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n  else root.EquipmentData = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n";
const target = path.join(root, 'equipment_data.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Run node tools/build-equipment-data.cjs');
} else fs.writeFileSync(target, output);
console.log(data.items.length + ' equipment records validated');
